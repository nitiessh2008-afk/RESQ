@st.cache_data(ttl=300, show_spinner=False)
def get_rainviewer_radar_tile_path():

    fallback = (
        "https://tilecache.rainviewer.com/"
        "v2/radar/live/256/"
        "{z}/{x}/{y}/2/1_1.png"
    )

    try:

        url = (
            "https://api.rainviewer.com/"
            "public/weather-maps.json"
        )

        req = urllib.request.Request(
            url,
            headers={
                "User-Agent": "ResQ-Live-Radar/4.0"
            },
        )

        with urllib.request.urlopen(req, timeout=7) as response:

            data = json.loads(
                response.read().decode("utf-8")
            )

        host = data.get(
            "host",
            "https://tilecache.rainviewer.com"
        )

        past_radar = (
            data.get("radar", {})
            .get("past", [])
        )

        if past_radar:

            latest_path = past_radar[-1].get("path")

            if latest_path:

                return (
                    f"{host}{latest_path}"
                    "/256/{z}/{x}/{y}/2/1_1.png"
                )

    except Exception:
        pass

    return fallback


