@st.cache_data(ttl=900, show_spinner=False)
def fetch_nasa_gibs_satellite_image(
    bbox,
    layer="VIIRS_SNPP_CorrectedReflectance_TrueColor",
    target_date=None,
):

    if target_date is None:
        target_date = (
            datetime.utcnow() - timedelta(days=1)
        ).strftime("%Y-%m-%d")

    params = {
        "SERVICE": "WMS",
        "REQUEST": "GetMap",
        "LAYERS": layer,
        "FORMAT": "image/jpeg",
        "HEIGHT": "480",
        "WIDTH": "740",
        "VERSION": "1.1.1",
        "SRS": "EPSG:4326",
        "BBOX": bbox,
        "TIME": target_date,
    }

    base_url = (
        "https://gibs.earthdata.nasa.gov/wms/"
        "epsg4326/best/wms.cgi"
    )

    url = base_url + "?" + urllib.parse.urlencode(params)

    try:

        req = urllib.request.Request(
            url,
            headers={
                "User-Agent": "ResQ-Live-Satellite/4.0"
            },
        )

        with urllib.request.urlopen(req, timeout=10) as response:

            content_type = response.headers.get(
                "Content-Type",
                ""
            )

            if response.status == 200 and "image" in content_type:

                image_data = response.read()

                image = Image.open(
                    io.BytesIO(image_data)
                )

                return (
                    image,
                    url,
                    "NASA Earthdata GIBS",
                )

    except Exception:
        pass

    return (
        None,
        url,
        "NASA GIBS Endpoint",
    )


