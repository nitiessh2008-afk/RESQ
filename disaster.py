@st.cache_data(ttl=900, show_spinner=False)
def fetch_nasa_gibs_satellite_image(
    bbox,
    layer="VIIRS_SNPP_CorrectedReflectance_TrueColor",
    target_date=None,
):

    if not target_date:

        target_date = (
            datetime.now() - timedelta(days=1)
        ).strftime("%Y-%m-%d")

    url = (
        "https://gibs.earthdata.nasa.gov/wms/"
        "epsg4326/best/wms.cgi?"
        "SERVICE=WMS&"
        "REQUEST=GetMap&"
        f"LAYERS={layer}&"
        "FORMAT=image/jpeg&"
        "HEIGHT=480&"
        "WIDTH=740&"
        "VERSION=1.1.1&"
        "SRS=EPSG:4326&"
        f"BBOX={bbox}&"
        f"TIME={target_date}"
    )

    try:

        req = urllib.request.Request(
            url,
            headers={
                "User-Agent":
                    "Mozilla/5.0 ResQ-Live-Satellite"
            },
        )

        with urllib.request.urlopen(
            req,
            timeout=8,
        ) as response:

            content_type = response.headers.get(
                "Content-Type",
                "",
            )

            if (
                response.status == 200
                and "image" in content_type
            ):

                img_data = response.read()

                return (
                    Image.open(
                        io.BytesIO(img_data)
                    ),
                    url,
                    "NASA Earthdata GIBS",
                )

    except Exception:
        pass

    return (
        None,
        url,
        "NASA GIBS Endpoint",
    )


