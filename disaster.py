@st.cache_data(ttl=600, show_spinner=False)
def fetch_live_meteorological_telemetry(lat, lon):

    base_url = "https://api.open-meteo.com/v1/forecast"

    params = {
        "latitude": lat,
        "longitude": lon,
        "current": (
            "temperature_2m,"
            "relative_humidity_2m,"
            "precipitation,"
            "wind_speed_10m,"
            "surface_pressure"
        ),
    }

    url = base_url + "?" + urllib.parse.urlencode(params)

    try:
        req = urllib.request.Request(
            url,
            headers={
                "User-Agent": "ResQ-Live-Disaster-Portal/4.0"
            },
        )

        with urllib.request.urlopen(req, timeout=8) as response:
            data = json.loads(
                response.read().decode("utf-8")
            )

        current = data.get("current", {})

        return {
            "success": True,
            "temperature": float(
                current.get("temperature_2m", 28.5)
            ),
            "humidity": float(
                current.get("relative_humidity_2m", 82)
            ),
            "precipitation": float(
                current.get("precipitation", 0.0)
            ),
            "wind_speed": float(
                current.get("wind_speed_10m", 15.0)
            ),
            "pressure": float(
                current.get("surface_pressure", 1008.0)
            ),
            "timestamp": current.get(
                "time",
                datetime.now().strftime("%Y-%m-%dT%H:%M")
            ),
            "source": "Open-Meteo Live Weather Telemetry",
        }

    except Exception as exc:

        return {
            "success": False,
            "temperature": 29.2,
            "humidity": 84.0,
            "precipitation": 0.0,
            "wind_speed": 20.0,
            "pressure": 1005.0,
            "timestamp": datetime.now().strftime(
                "%Y-%m-%dT%H:%M"
            ),
            "source": "Telemetry Standby / API Unavailable",
            "error": str(exc),
        }


